// Deep merge helper
function deepMerge(target, source) {
  const result = { ...target };
  for (const key of Object.keys(source)) {
    if (source[key] && typeof source[key] === 'object' && !Array.isArray(source[key])) {
      result[key] = deepMerge(target[key] || {}, source[key]);
    } else {
      result[key] = source[key];
    }
  }
  return result;
}

// Build dictionary for an extra language with Hindi/English fallback
function buildCompleteLanguage(code) {
  const custom = extraLanguages[code];
  if (!custom) return { ...en };
  const base = en;
  const merged = deepMerge(base, custom);
  delete merged.name;
  delete merged.direction;
  return merged;
}

