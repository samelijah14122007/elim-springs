export const APP_SUPPORTED_LANGUAGES = ALL_INDIAN_LANGUAGES.map((l) => ({
  code: l.code,
  name: l.name,
  nativeName: l.nativeName,
  script: l.script,
  direction: l.direction,
}));

export const getLanguageDefinition = (code: LanguageCode): IndianLanguageDefinition => {
  const found = ALL_INDIAN_LANGUAGES.find((l) => l.code === code);
  return found || ALL_INDIAN_LANGUAGES[0]; // fallback to English
};

export const isRtlLanguage = (code: LanguageCode): boolean => {
  return code === 'ur' || code === 'ks' || code === 'sd';
};
